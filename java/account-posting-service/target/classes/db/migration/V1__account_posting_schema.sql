-- account-posting-service owns accounts, card xref, the fee ledger and its outbox.

CREATE TABLE ACCOUNT (
    ACCT_ID DECIMAL(11,0) PRIMARY KEY,
    ACTIVE_STATUS VARCHAR(1) NOT NULL,
    CURR_BAL DECIMAL(12,2) NOT NULL,
    CREDIT_LIMIT DECIMAL(12,2) NOT NULL,
    CASH_CREDIT_LIMIT DECIMAL(12,2) NOT NULL,
    OPEN_DATE VARCHAR(10) NOT NULL,
    EXPIRATION_DATE VARCHAR(10) NOT NULL,
    REISSUE_DATE VARCHAR(10) NOT NULL,
    CURR_CYC_CREDIT DECIMAL(12,2) NOT NULL,
    CURR_CYC_DEBIT DECIMAL(12,2) NOT NULL,
    ADDR_ZIP VARCHAR(10) NOT NULL,
    GROUP_ID VARCHAR(10) NOT NULL
);

CREATE TABLE CARD_XREF (
    CARD_NUM CHAR(16) PRIMARY KEY,
    CUST_ID DECIMAL(9,0) NOT NULL,
    ACCT_ID DECIMAL(11,0) NOT NULL
);

-- Verbatim from db2/ddl/XFER_FEE_LEDGER.sql (checked by FlywaySchemaTest).
CREATE TABLE XFER_FEE_LEDGER (
    TRAN_ID CHAR(16) PRIMARY KEY,
    TRAN_DT DATE NOT NULL,
    SRC_ACCT_ID DECIMAL(11,0) NOT NULL,
    TGT_ACCT_ID DECIMAL(11,0) NOT NULL,
    BOOK_ID CHAR(10) NOT NULL,
    TRAN_AMT DECIMAL(11,2) NOT NULL,
    FEE_AMT DECIMAL(11,2) NOT NULL,
    CAP_APPLIED CHAR(1) NOT NULL,
    POSTED_TS TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE POSTING_OUTBOX (
    EVENT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AGGREGATE_ID VARCHAR(16) NOT NULL,
    EVENT_TYPE VARCHAR(40) NOT NULL,
    PAYLOAD VARCHAR(4000) NOT NULL,
    CREATED_TS TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PUBLISHED_TS TIMESTAMP
);
